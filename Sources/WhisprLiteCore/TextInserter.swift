import AppKit
import ApplicationServices
import Carbon

struct ClipboardSnapshot: Sendable, Equatable {
    let items: [[String: Data]]
    init(items: [[String: Data]]) { self.items = items }
}
@MainActor protocol ClipboardAccess: AnyObject {
    var changeCount: Int { get }
    var text: String? { get }
    func snapshot() throws -> ClipboardSnapshot
    /// Writes text that reports when another app first reads it. Without that signal the
    /// transaction falls back to its timeout.
    func write(_ text: String, onRead: @escaping @MainActor () -> Void) throws
    func restore(_ snapshot: ClipboardSnapshot) throws
}
@MainActor public final class ClipboardTransaction {
    private struct Pending {
        let snapshot: ClipboardSnapshot
        let changeCount: Int
        let text: String
        let session: UUID?
    }
    private let clipboard: any ClipboardAccess
    private var pending: Pending?
    private var serial: UInt64 = 0
    var onRestore: ((UUID?, DiagnosticCode) -> Void)?
    private var restoreTask: Task<Void, Never>?
    init(_ clipboard: any ClipboardAccess) { self.clipboard = clipboard }
    /// Restores shortly after the target reads the pasted text, so the old clipboard returns
    /// quickly and a slow target still gets the dictation. `delay` covers a target that never reads.
    func write(_ text: String, delay: Duration = .milliseconds(1500), afterRead: Duration = .milliseconds(100),
                      session: UUID? = nil) throws {
        settle()
        let snapshot = try clipboard.snapshot()
        serial &+= 1; let owner = serial
        try clipboard.write(text) { [weak self] in self?.read(owner, grace: afterRead) }
        pending = Pending(snapshot: snapshot, changeCount: clipboard.changeCount, text: text, session: session)
        scheduleSettle(after: delay)
    }
    private func scheduleSettle(after delay: Duration) {
        restoreTask?.cancel()
        restoreTask = Task { [weak self] in
            do { try await Task.sleep(for: delay) } catch { return }
            self?.settle()
        }
    }
    /// Grace for apps that read several types in one paste.
    private func read(_ owner: UInt64, grace: Duration) {
        guard serial == owner, pending != nil else { return }
        scheduleSettle(after: grace)
    }
    public func settle() {
        restoreTask?.cancel(); restoreTask = nil
        guard let pending else { return }
        self.pending = nil
        if clipboard.changeCount == pending.changeCount, clipboard.text == pending.text {
            do { try clipboard.restore(pending.snapshot); onRestore?(pending.session, .restored) }
            catch { onRestore?(pending.session, .restoreFailed) }
        } else { onRestore?(pending.session, .userClipboardChanged) }
    }
}
/// Supplies the dictation on demand, which is how the transaction learns the paste was read.
private final class PromisedText: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
    let text: String
    let onRead: @MainActor () -> Void
    init(_ text: String, onRead: @escaping @MainActor () -> Void) { self.text = text; self.onRead = onRead }
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        item.setString(text, forType: type)
        let onRead = onRead
        Task { @MainActor in onRead() }
    }
}
@MainActor final class SystemClipboard: ClipboardAccess {
    private let pasteboard: NSPasteboard
    private var promise: PromisedText?
    /// nspasteboard.org markers: clipboard managers skip restored, app-generated content,
    /// so dictation doesn't enter their history and they don't read it before the target does.
    static let transientTypes = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                                 NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]
    init(_ pasteboard: NSPasteboard = .general) { self.pasteboard = pasteboard }
    var changeCount: Int { pasteboard.changeCount }
    var text: String? { pasteboard.string(forType: .string) }
    func snapshot() throws -> ClipboardSnapshot {
        var total = 0
        var result: [[String: Data]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var types: [String: Data] = [:]
            for type in item.types {
                guard !type.rawValue.lowercased().contains("promise") else { throw AppError.clipboard }
                guard let data = item.data(forType: type) else { throw AppError.clipboard }
                total += data.count
                guard total <= 8 * 1024 * 1024 else { throw AppError.clipboard }
                types[type.rawValue] = data
            }
            result.append(types)
        }
        return .init(items: result)
    }
    func write(_ text: String, onRead: @escaping @MainActor () -> Void) throws {
        let promise = PromisedText(text, onRead: onRead), item = NSPasteboardItem()
        guard item.setDataProvider(promise, forTypes: [.string]) else { throw AppError.clipboard }
        try write(item); self.promise = promise
    }
    private func write(_ item: NSPasteboardItem) throws {
        for type in Self.transientTypes { item.setData(Data(), forType: type) }
        promise = nil
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else { throw AppError.clipboard }
    }
    func restore(_ snapshot: ClipboardSnapshot) throws {
        let items = snapshot.items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: .init(type)) }
            return item
        }
        pasteboard.clearContents()
        if !items.isEmpty, !pasteboard.writeObjects(items) { throw AppError.clipboard }
    }
}
@MainActor public final class TextInserter: InsertionDriver {
    private struct Target {
        let id: UUID
        let session: UUID
        let pid: pid_t
        let kind: InsertionTargetKind
        let element: AXUIElement?
    }
    private var target: Target?
    public let clipboard: ClipboardTransaction
    public var diagnostics: DiagnosticLogger? { didSet { updateRestoreObserver() } }
    public var timings: LatencyRecorder? { didSet { updateRestoreObserver() } }
    private let modifierGate = ModifierReleaseGate()
    /// AX calls are synchronous IPC on the main actor. Bound a hung target well below the
    /// 6-second system default; slow-but-working apps (first Chromium query) stay well inside it.
    private static let messagingTimeout: Float = 1
    public init() { clipboard = ClipboardTransaction(SystemClipboard()) }
    init(clipboard: ClipboardTransaction) { self.clipboard = clipboard }
    private func updateRestoreObserver() {
        guard diagnostics?.isEnabled == true || timings?.isEnabled == true else {
            clipboard.onRestore = nil
            return
        }
        clipboard.onRestore = { [weak self] session, code in
            guard let self else { return }
            self.diagnostics?.record(.init(.clipboardRestore, session: session, code: code))
            if code == .restored, let session { self.timings?.mark(.clipboardRestored, session: session) }
        }
    }
    private func focused(_ pid: pid_t) -> AXUIElement? {
        var value: CFTypeRef?
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, Self.messagingTimeout)
        guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        let element = value as! AXUIElement
        AXUIElementSetMessagingTimeout(element, Self.messagingTimeout)
        return element
    }
    private func attribute(_ element: AXUIElement, _ name: String) -> CFTypeRef? {
        var value: CFTypeRef?
        return AXUIElementCopyAttributeValue(element, name as CFString, &value) == .success ? value : nil
    }
    public func snapshot(session: UUID) -> UUID {
        let app = NSWorkspace.shared.frontmostApplication
        let id = UUID(), pid = app?.processIdentifier ?? 0
        let kind = InsertionTargetKind.classify(bundleIdentifier: app?.bundleIdentifier)
        let captured = Target(id: id, session: session, pid: pid, kind: kind,
                              element: pid == 0 ? nil : focused(pid))
        target = captured
        diagnostics?.record(.init(.targetSnapshot, session: captured.session, target: captured.kind))
        return id
    }
    private func validate(_ target: Target) throws -> AXUIElement {
        func reject(_ code: DiagnosticCode) throws -> Never {
            diagnostics?.record(.init(.insertionCheck, session: target.session, code: code))
            throw AppError.targetChanged
        }
        guard AXIsProcessTrusted() else { try reject(.accessibilityDenied) }
        guard target.pid != 0 else { try reject(.noTarget) }
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == target.pid else { try reject(.appChanged) }
        guard let saved = target.element, let current = focused(target.pid), CFEqual(saved, current) else { try reject(.elementChanged) }
        // One round trip for all four checks; a missing attribute reads as nil, as a single copy would.
        let names = [kAXEnabledAttribute, kAXSubroleAttribute, kAXRoleAttribute, "AXEditable"]
        var copied: CFArray?
        var values = [AnyObject?](repeating: nil, count: names.count)
        if AXUIElementCopyMultipleAttributeValues(current, names as CFArray, [], &copied) == .success,
           let array = copied as? [AnyObject], array.count == names.count { values = array }
        guard values[0] as? Bool != false else { try reject(.disabledTarget) }
        guard values[1] as? String != kAXSecureTextFieldSubrole else { try reject(.secureTarget) }
        guard let role = values[2] as? String,
              [kAXTextFieldRole, kAXTextAreaRole, kAXComboBoxRole].contains(role) else { try reject(.unsupportedRole) }
        guard values[3] as? Bool != false else { try reject(.readonlyTarget) }
        // Cmd-V requires a focused paste destination, not writable AXValue/SelectedText.
        // Terminals and several custom editors expose read-only accessibility text.
        diagnostics?.record(.init(.insertionCheck, session: target.session, code: .ready))
        return current
    }
    public func insert(_ text: String, target id: UUID) async throws {
        guard let target, target.id == id else {
            diagnostics?.record(.init(.insertionCheck, code: .noTarget))
            throw AppError.targetChanged
        }
        self.target = nil
        var modifierDecision: ((CGEventFlags, Duration) -> Void)?
        if let diagnostics, diagnostics.isEnabled {
            let session = target.session
            modifierDecision = { flags, elapsed in
                guard diagnostics.isEnabled else { return }
                var record = DiagnosticRecord(.modifierState, session: session, code: flags.isEmpty ? .ready : .modifiersHeld,
                    milliseconds: elapsed.milliseconds)
                record.hardwareModifiers = InsertionModifier.held(in: flags)
                record.sessionModifiers = InsertionModifier.held(in: CGEventSource.flagsState(.combinedSessionState))
                diagnostics.record(record)
            }
        }
        do { try await modifierGate.wait(onDecision: modifierDecision) }
        catch AppError.modifiersHeld {
            diagnostics?.record(.init(.insertionCheck, session: target.session, code: .modifiersHeld))
            throw AppError.modifiersHeld
        }
        try Task.checkCancellation()
        let element = try validate(target)
        // AX range writes are opt-in only for our controlled benchmark target until third-party validation.
        if target.pid == getpid() {
            var settable = DarwinBoolean(false)
            if AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &settable) == .success, settable.boolValue,
               attribute(element, kAXSelectedTextRangeAttribute) != nil {
                let status = AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString)
                // Once attempted, never fall through to a second ambiguous insertion.
                guard status == .success else { throw AppError.targetChanged }
                diagnostics?.record(.init(.insertionMethod, session: target.session, code: .nativeAX))
                return
            }
        }
        guard let code = Self.pasteKeyCode(), let (down, up) = Self.pasteEvents(keyCode: code) else { throw AppError.unsupported }
        try clipboard.write(text, session: target.session)
        for event in [down, up] {
            // Session injection leaves the hardware state used by the gate alone.
            event.post(tap: .cgSessionEventTap)
        }
        diagnostics?.record(.init(.insertionMethod, session: target.session, code: .commandPaste))
    }
    static func pasteEvents(keyCode: CGKeyCode) -> (CGEvent, CGEvent)? {
        guard let source = CGEventSource(stateID: .privateState),
              let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false) else { return nil }
        for event in [down, up] {
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: injectedEventMarker)
        }
        return (down, up)
    }
    /// Search the active Command-modified layout; includes Dvorak-QWERTY Command layouts.
    static func pasteKeyCode() -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue()
        guard let bytes = CFDataGetBytePtr(data) else { return nil }
        let layout = UnsafeRawPointer(bytes).assumingMemoryBound(to: UCKeyboardLayout.self)
        var chars = [UniChar](repeating: 0, count: 8)
        for code: UInt16 in 0..<128 {
            var dead: UInt32 = 0; var length = 0
            let result = UCKeyTranslate(layout, code, UInt16(kUCKeyActionDown), UInt32(cmdKey >> 8), UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysMask), &dead, 8, &length, &chars)
            // A one-unit translated Command-V is ASCII v or V; no String is needed per key.
            if result == noErr && length == 1 && (chars[0] == 0x76 || chars[0] == 0x56) {
                return code
            }
        }
        return nil
    }
}
