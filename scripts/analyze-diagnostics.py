#!/usr/bin/env python3
"""Summarize opt-in Whispr Lite timings and failure codes; never print user content."""
import argparse
from collections import Counter, defaultdict
import json
import math
from pathlib import Path
import statistics

SPANS = {
    'release → capture drain': ('release', 'captureFinalized'),
    'capture worker first audio': ('press', 'firstAudio'),
    'ASR': ('asrStart', 'asrEnd'),
    'cleanup': ('cleanupStart', 'cleanupEnd'),
    'result → insertion dispatch': ('resultReady', 'insertionDispatched'),
    'release → insertion dispatch': ('release', 'insertionDispatched'),
    'insertion → clipboard restoration': ('insertionDispatched', 'clipboardRestored'),
    'media pause request → confirmed pause': ('mediaBegin', 'mediaPaused'),
    'media end request → Play submission': ('mediaEnd', 'mediaReleased'),
    'media end request → confirmed resume': ('mediaEnd', 'mediaResumed'),
}
MEDIA_STAGES = {'begin': 'mediaBegin', 'end': 'mediaEnd', 'paused': 'mediaPaused',
                'released': 'mediaReleased', 'resumed': 'mediaResumed'}
MEDIA_REASONS = {'playerChanged', 'playerRestarted', 'itemChanged', 'itemIdentifierRefreshed', 'unidentifiedPlayer',
                 'unknownPlayer', 'externalPlayback', 'subscriptionUnavailable', 'alreadyPaused',
                 'endedBeforePause', 'closing', 'leaseBusy', 'noLease', 'sessionMismatch',
                 'pauseRejected', 'pauseUnconfirmed', 'resumeRejected', 'resumeUnconfirmed', 'queryTimeout'}
MODIFIERS = {'command', 'control', 'option', 'shift', 'fn'}
CAPTURE_FAILURES = {'gap', 'overflow', 'oversize', 'converter', 'full', 'notRecording', 'notPrepared',
                    'permission', 'engineStart', 'busy'}
COVERAGE_OUTCOMES = {'unavailable', 'noWords', 'covered', 'uncovered', 'recovered', 'unrecovered'}
COVERAGE_FIELDS = ('audioSeconds', 'lastWordEndSeconds', 'speechAfterSeconds', 'recoveredWords', 'fallbackMS')
CAPTURE_FIELDS = ('idleSeconds', 'engineStartMS', 'engineStatus', 'firstPacketMS', 'packets', 'settlingGaps',
                  'settlingGapMS', 'gaps', 'firstGapAtMS', 'largestGapMS', 'droppedPackets', 'oversizePackets',
                  'maxCallbackMS', 'maxQueueDelayMS')

def number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)

def capture_line(report):
    failure = report.get('failure')
    parts = [f'failure={failure if failure in CAPTURE_FAILURES else "none"}']
    parts += [f'{key}={report[key]:.1f}' if isinstance(report[key], float) else f'{key}={report[key]}'
              for key in CAPTURE_FIELDS if number(report.get(key))]
    return ' '.join(parts)

def modifier_names(value):
    if not isinstance(value, list) or len(value) > 5: return ()
    return tuple(sorted({name for name in value if isinstance(name, str) and name in MODIFIERS}))

def summarize(directory):
    sessions = defaultdict(dict)
    reasons = Counter()
    media = Counter()
    outcomes = Counter()
    modifiers = Counter()
    modifier_waits = []
    captures = []
    coverage = []
    total = dropped = 0
    for name in ('debug.previous.jsonl', 'debug.jsonl'):
        path = directory / name
        if not path.exists(): continue
        if path.stat().st_size > 4 * 1024 * 1024: raise ValueError('Log exceeds the expected bound')
        for line in path.read_text().splitlines():
            if len(line) > 8192: raise ValueError('Oversized diagnostic record')
            event = json.loads(line); total += 1
            dropped = max(dropped, event.get('droppedBefore', 0))
            if event.get('kind') == 'timing' and event.get('session'):
                stage = event.get('stage')
                if any(stage in pair for pair in SPANS.values()): sessions[event['session']][stage] = event['milliseconds']
            if event.get('kind') in ('mediaCommand', 'mediaReply') and event.get('session'):
                stage = MEDIA_STAGES.get(event.get('code'))
                if stage and 'uptimeMS' in event: sessions[event['session']][stage] = event['uptimeMS']
            if event.get('kind') in ('failure', 'preparationFailed', 'insertionCheck', 'clipboardRestore') or (
                    event.get('kind') == 'capture' and 'code' in event):
                code = event.get('code', 'unknown')
                # Only constant codes generated by this app are ever displayed.
                if isinstance(code, str) and code.isascii() and code.isalpha() and len(code) <= 40:
                    reasons[(event['kind'], code)] += 1
            if event.get('kind') == 'mediaReply':
                reason = event.get('mediaReason')
                if reason in MEDIA_REASONS:
                    reasons[('mediaReply', reason)] += 1
                code = event.get('code')
                if code in ('issued', 'paused', 'released', 'resumed', 'skipped', 'unconfirmed', 'fatal'):
                    outcomes[code] += 1
                media[(event.get('known') is True or event.get('known') == 1,
                       event.get('playing') is True, event.get('trustworthy') is True or event.get('trustworthy') == 1,
                       event.get('subscriptionHealthy') is True or event.get('subscriptionHealthy') == 1)] += 1
            if event.get('kind') == 'capture' and isinstance(event.get('capture'), dict):
                captures.append(event['capture'])
            if event.get('kind') == 'coverage' and isinstance(event.get('coverage'), dict) \
                    and event['coverage'].get('outcome') in COVERAGE_OUTCOMES:
                coverage.append(event['coverage'])
            if event.get('kind') == 'modifierState':
                modifiers[(modifier_names(event.get('hardwareModifiers')), modifier_names(event.get('sessionModifiers')))] += 1
                value = event.get('milliseconds')
                if isinstance(value, (int, float)) and math.isfinite(value) and value >= 0: modifier_waits.append(value)
    print(f'{total} diagnostic records; {len(sessions)} timed sessions; dropped-event high water {dropped}')
    print('Timings measure app stages and insertion dispatch, not actual visibility in another app.')
    for label, (start, end) in SPANS.items():
        values = sorted(s[end] - s[start] for s in sessions.values() if start in s and end in s and s[end] >= s[start])
        if values:
            p95 = values[math.ceil(len(values) * .95) - 1]
            print(f'{label}: n={len(values)} median={statistics.median(values):.2f} ms p95={p95:.2f} ms')
    for (kind, code), count in sorted(reasons.items()): print(f'{kind}/{code}: {count}')
    for code, count in sorted(outcomes.items()): print(f'media outcome/{code}: {count}')
    if captures:
        failed = [report for report in captures if report.get('failure') in CAPTURE_FAILURES]
        settling = sum(1 for report in captures if number(report.get('settlingGaps')) and report['settlingGaps'] > 0)
        print(f'capture reports: n={len(captures)} failed={len(failed)} with startup gaps={settling}')
        for key in ('idleSeconds', 'firstPacketMS', 'maxCallbackMS', 'maxQueueDelayMS'):
            values = sorted(report[key] for report in captures if number(report.get(key)))
            if values: print(f'capture {key}: n={len(values)} median={statistics.median(values):.2f} max={values[-1]:.2f}')
        for report in failed[-10:]: print(f'failed capture: {capture_line(report)}')
    if coverage:
        print('transcript coverage: ' + ' '.join(f'{outcome}={count}' for outcome, count in
                                                  sorted(Counter(report['outcome'] for report in coverage).items())))
        # A stitched transcript that stops short of the speech is what the tail fallback is for.
        for report in [r for r in coverage if r['outcome'] in ('uncovered', 'recovered', 'unrecovered')][-10:]:
            print(f"coverage {report['outcome']}: " + ' '.join(f'{key}={report[key]:.2f}' if isinstance(report[key], float)
                  else f'{key}={report[key]}' for key in COVERAGE_FIELDS if number(report.get(key))))
    if modifier_waits:
        modifier_waits.sort()
        print(f'physical modifier release wait: n={len(modifier_waits)} median={statistics.median(modifier_waits):.2f} ms p95={modifier_waits[math.ceil(len(modifier_waits) * .95) - 1]:.2f} ms')
    for (hardware, session), count in sorted(modifiers.items()):
        print(f'modifier guard: hardware={",".join(hardware) or "none"} session={",".join(session) or "none"} count={count}')
    for (known, playing, trusted, subscribed), count in sorted(media.items()):
        print(f'media reply: known={known} playing={playing} identifiable={trusted} subscription={subscribed} count={count}')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path, nargs='?', default=Path.home() / 'Library/Application Support/WhisprLite/Diagnostics')
    args = parser.parse_args()
    try: summarize(args.directory)
    except (OSError, ValueError, KeyError, TypeError) as error: parser.exit(1, f'Cannot analyze diagnostics: {type(error).__name__}\n')
